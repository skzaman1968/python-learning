# Variables and Data Types

name = "Alice"
age = 25
height = 5.6
is_student = True

print("Name:", name)
print("Age:", age)
print("Height:", height)
print("Is student:", is_student)

# Type checking
print(type(name))
print(type(age))
print(type(height))
print(type(is_student))

# Multiple assignment
x, y, z = 10, 20, 30
print(x, y, z)

# Swapping
x, y = y, x
print("After swap:", x, y)
